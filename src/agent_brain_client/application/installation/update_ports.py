"""Maintenance ports; registration, package storage and native hooks stay outside."""

from contextlib import AbstractContextManager
from dataclasses import dataclass
from typing import Protocol


class ManagedConfigurationConflict(ValueError):
    def __init__(self, field: str):
        self.field = field
        super().__init__("Managed configuration conflict")


class HostEditInProgress(ValueError):
    pass


@dataclass(frozen=True)
class RegisteredInstallation:
    platform: str
    supported: bool
    launcher: dict


class UpdateChannel(Protocol):
    def verified_active(self) -> dict | None: ...
    def discover(self, adapter: str, platform: str, installed: str) -> dict: ...
    def update(self) -> dict: ...


class UpdateInstallation(Protocol):
    mcp_config_field: str
    check_command: str
    update_command: str

    def recover_hooks(self, *, check_only: bool) -> bool: ...
    def handover_pending(self) -> bool: ...
    def refresh_launcher(
        self, *, channel: UpdateChannel | None = None, before: dict | None = None
    ) -> bool: ...
    def inspect(self) -> dict: ...
    def load_registration(self) -> RegisteredInstallation: ...
    def environment(self) -> AbstractContextManager: ...
    def open_channel(self) -> UpdateChannel: ...
    def tool_discovery(self, active: dict) -> dict: ...
    def launcher_update_available(self, version: str, commit: str) -> bool: ...
    def refresh_hooks(self, *, check_only: bool = False) -> dict: ...
    def collection_installed(self) -> bool: ...
    def install_collection(self) -> dict: ...
    def setup_sources(self) -> dict: ...

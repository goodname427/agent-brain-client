"""Storage-neutral refresh contracts. Native mapping owns transaction recovery."""

from contextlib import AbstractContextManager
from typing import Protocol


class Mapping(Protocol):
    def recover(self) -> None: ...
    def recovery_uncertain(self) -> bool: ...
    def owned_snapshot(self) -> dict: ...
    def apply_snapshot(self, snapshot: dict, owned: dict, progress: dict) -> dict: ...


class SourceImports(Protocol):
    def reconcile_pending(self) -> None: ...
    def import_status(self) -> dict: ...


class ContentRefresh(Protocol):
    mapping: Mapping
    sources: SourceImports

    def ensure_refresh_available(self) -> None: ...
    def refresh_transaction(self) -> AbstractContextManager: ...
    def replay_writes(self) -> None: ...
    def queue_status(self) -> dict: ...
    def fetch_snapshot(self) -> dict: ...


class NativeSourceProvider(Protocol):
    prefix: str

    def inventory(self) -> dict: ...
    def read(self, source_id: str) -> bytes: ...


class NativeContentHost(Protocol):
    """Only native rendering, source discovery and owned configuration removal."""

    name: str
    protected: tuple[str, ...]

    def default_home(self, home): ...
    def binding(self, home, native) -> dict: ...
    def location(self, home, runtime) -> tuple: ...
    def mapping(self, session) -> Mapping: ...
    def sources(self, session) -> NativeSourceProvider: ...
    def remove_hooks(self, home, raw: bytes, platform: str) -> tuple: ...
    def detach_payload(self, home, native, metadata, *, installed=True) -> dict: ...
